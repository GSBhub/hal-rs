"""PeakRDL exporters for HALucinator, after Antmicro's pair for Renode.

Antmicro ship two PeakRDL plugins in the Renode repo (tools/PeakRDL-renode and
tools/PeakRDL-repl): one turns an addrmap into a peripheral model, the other
into a platform description. These are the HALucinator counterparts:

    peakrdl halucinator        soc.rdl -o soc_regs.py     # avatar2 peripheral models
    peakrdl halucinator-memory soc.rdl -o soc_memory.yaml --module soc_regs

``halrs models`` does the same from an SVD (or RDL) without PeakRDL.

The model module needs only avatar2, so stock HALucinator can use it as well as
hal-rs. Its classes behave like hal-rs's Rust register model, status-bit hints
included (see rdl_peripheral.py).
"""

from __future__ import annotations

import inspect
from pathlib import Path

from systemrdl.node import AddrmapNode, RootNode

from ..ir import Hint, Mirror, Peripheral
from ..rdl import peripherals
from . import rdl_peripheral

_CONST = {rdl_peripheral.RW: "RW", rdl_peripheral.RO: "RO", rdl_peripheral.WO: "WO",
          rdl_peripheral.W1C: "W1C", rdl_peripheral.RC: "RC"}


Source = RootNode | AddrmapNode | list[Peripheral]


def _peripherals(src: Source) -> list[Peripheral]:
    if isinstance(src, list):
        return src
    return peripherals(src.top if isinstance(src, RootNode) else src)


def _hint(h) -> str:
    if isinstance(h, Mirror):
        return str(h.mirror)
    return {Hint.POLL_SET: "POLL_SET", Hint.POLL_CLEAR: "POLL_CLEAR"}.get(h, "None")


def _class(p: Peripheral) -> str:
    lines = [f"class {p.name}(RdlPeripheral):",
             f"    IRQS = ({''.join(f'{i}, ' for i in p.irqs).rstrip()})",
             "    REGISTERS = {"]
    for r in sorted(p.registers, key=lambda r: r.offset):
        fields = "".join(
            f"\n            ({f.name!r}, {f.lsb}, {f.width}, {_CONST[f.access.value]}, {_hint(f.hint)}),"
            for f in r.fields)
        lines.append(f"        {r.offset:#x}: ({r.name!r}, {max(r.size // 8, 1)}, {r.reset:#x}, ({fields}\n        )),")
    lines.append("    }")
    return "\n".join(lines)


def model_source(src: Source, source: str = "") -> str:
    """Python module of avatar2 peripherals, one class per peripheral."""
    ps = _peripherals(src)
    runtime = inspect.getsource(rdl_peripheral)
    head = (f"# Generated by hal-rs{f' from {source}' if source else ''} "
            "(`peakrdl halucinator` / `halrs models`).\n"
            "# Do not edit: subclass these in another module (see RdlPeripheral's docstring).\n\n")
    table = "PERIPHERALS = {%s}\n" % ", ".join(
        f"{p.name!r}: ({p.name}, {p.base:#x}, {p.size:#x})" for p in ps)
    bus = "\n\nclass Bus(RdlBus):\n    PERIPHERALS = PERIPHERALS\n"
    return head + runtime + "\n\n" + "\n\n\n".join(_class(p) for p in ps) + "\n\n\n" + table + bus


PAGE = 0x1000   # avatar2/HALucinator memory granularity


def windows(ps: list[Peripheral]) -> list[tuple[int, int, list[str]]]:
    """Page-aligned (base, size, peripheral names), adjacent pages merged."""
    pages: dict[int, list[str]] = {}
    for p in ps:
        for page in range(p.base & ~(PAGE - 1), p.base + max(p.size, 1), PAGE):
            pages.setdefault(page, []).append(p.name)
    out: list[tuple[int, int, list[str]]] = []
    for page in sorted(pages):
        if out and out[-1][0] + out[-1][1] == page:
            base, size, names = out[-1]
            out[-1] = (base, size + PAGE, names + [n for n in pages[page] if n not in names])
        else:
            out.append((page, PAGE, list(pages[page])))
    return out


def memory_source(src: Source, module: str | None = None,
                  source: str = "") -> str:
    """HALucinator memory-config YAML: ``peripherals:`` entries for page-aligned
    windows (see ``windows``), each a ``Bus`` over the peripherals in it.
    ``module``: where the generated models live (else GenericPeripheral)."""
    lines = [f"# Generated by hal-rs{f' from {source}' if source else ''} "
             "(`peakrdl halucinator-memory` / `halrs models --memory`).",
             "peripherals:"]
    emulate = f"{module}.Bus" if module else "GenericPeripheral"
    for base, size, names in windows(_peripherals(src)):
        lines.append(f"  # {', '.join(names)}")
        lines.append(f"  periph_{base:08x}: {{base_addr: {base:#x}, size: {size:#x}, "
                     f"permissions: rw-, emulate: {emulate}}}")
    return "\n".join(lines) + "\n"


def write(path: str | Path, text: str) -> None:
    Path(path).write_text(text, encoding="utf-8")
